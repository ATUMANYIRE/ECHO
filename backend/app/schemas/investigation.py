"""Pydantic schemas for AI Investigation, Evidence-Grounded Diagnosis, and Fix Verification."""

from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field
from app.schemas.execution import ExecutionResponse


class EvidenceSufficiency(str, Enum):
    SUFFICIENT = "sufficient"
    AMBIGUOUS = "ambiguous"
    INSUFFICIENT = "insufficient"


class ChallengeType(str, Enum):
    PREDICTION = "prediction"
    CONCEPTUAL = "conceptual"
    CODING = "coding"


class LearningChallenge(BaseModel):
    """Targeted learning exercise derived from diagnosed misconception."""

    id: str = Field(description="Unique challenge identifier")
    challenge_type: ChallengeType = Field(description="Type of educational challenge")
    question: str = Field(description="Prompt question for the student")
    code_context: Optional[str] = Field(default=None, description="Optional snippet context")
    options: Optional[List[str]] = Field(default=None, description="Multiple choice options if applicable")
    correct_answer: str = Field(description="Deterministic correct answer or expected response")
    explanation: str = Field(description="Why this answer is correct grounded in runtime facts")
    hint: str = Field(description="Scaffolded hint guiding student without giving answer away")


class InvestigationRequest(BaseModel):
    """Input payload submitted for AI diagnostic investigation."""

    code: str = Field(..., max_length=10000, description="Student Python source code")
    expected_behavior: str = Field(default="", max_length=2000, description="Student's natural language intent or expected output")
    execution: ExecutionResponse = Field(..., description="Genuine verified execution response from sandbox")
    comparison_execution: Optional[ExecutionResponse] = Field(default=None, description="Optional secondary execution (e.g. baseline or modified)")


class InvestigationResponse(BaseModel):
    """Structured, evidence-grounded diagnostic response."""

    investigation_id: str = Field(description="Unique investigation trace identifier")
    observed_behavior: str = Field(description="Objective summary of what code actually did at runtime")
    expected_behavior: str = Field(description="Interpreted intent of what student wanted to achieve")
    root_cause_hypothesis: str = Field(description="Core misconception or mechanical defect causing divergence")
    explanation: str = Field(description="Plain-language educational explanation")
    supporting_step_indices: List[int] = Field(default_factory=list, description="Step indices in verified trace supporting diagnosis")
    relevant_lines: List[int] = Field(default_factory=list, description="Source code line numbers involved")
    suggested_correction: str = Field(description="Proposed code correction")
    correction_rationale: str = Field(description="Why this proposed correction addresses the root cause")
    confidence_assessment: str = Field(description="Confidence or uncertainty statement")
    evidence_sufficiency: EvidenceSufficiency = Field(default=EvidenceSufficiency.SUFFICIENT, description="Sufficiency of provided trace and intent evidence")
    learning_challenges: List[LearningChallenge] = Field(default_factory=list, description="Targeted comprehension exercises")
    is_live_ai: bool = Field(default=False, description="Whether response was generated by live Gemini API or deterministic provider")
    model_identifier: str = Field(default="mock", description="AI model name or provider identifier")
    latency_ms: float = Field(default=0.0, description="Diagnosis generation latency in milliseconds")
    validation_warnings: List[str] = Field(default_factory=list, description="Server-side validation warnings on evidence citations")


class FixVerificationRequest(BaseModel):
    """Payload to safely test a suggested fix inside the disposable sandbox."""

    original_code: str = Field(..., max_length=10000, description="Original student code")
    suggested_code: str = Field(..., max_length=10000, description="AI or user proposed corrected code")
    expected_behavior: str = Field(default="", max_length=2000, description="Expected program outcome")


class FixVerificationResponse(BaseModel):
    """Result of executing the proposed correction in the isolated container."""

    is_verified: bool = Field(description="Whether the correction successfully ran and resolved the observed defect")
    status: str = Field(description="Execution termination status of the fix")
    original_output: str = Field(description="Terminal output from original execution")
    verified_output: str = Field(description="Terminal output produced by verified execution")
    matches_expectation: bool = Field(description="Whether output satisfies stated expected behavior")
    verification_summary: str = Field(description="Summary of comparative verification findings")
    execution: ExecutionResponse = Field(description="Full authoritative execution trace of the corrected program")
    disclaimer: str = Field(
        default="Passing observed checks verifies behavior for tested inputs but does not prove universal algorithm correctness.",
        description="Academic honesty notice"
    )


class AIProviderStatus(BaseModel):
    """Health and configuration readiness of the server-side AI provider."""

    is_configured: bool
    is_available: bool
    provider_name: str
    configured_model: str
    active_model: str
    message: str
